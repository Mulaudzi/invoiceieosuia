import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const sourceRoot = path.join(root, 'src');
const libraryEntry = path.join(root, 'node_modules', 'lucide-react', 'dist', 'esm', 'lucide-react.js');
const output = path.join(sourceRoot, 'lib', 'icons.ts');

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) return sourceFiles(target);
    return /\.(ts|tsx)$/.test(entry.name) && target !== output ? [target] : [];
  }));
  return nested.flat();
}

const files = await sourceFiles(sourceRoot);
const requested = new Set();
const importPattern = /import\s*{([^}]*)}\s*from\s*['"]lucide-react['"];?/g;

for (const file of files) {
  const contents = await readFile(file, 'utf8');
  for (const match of contents.matchAll(importPattern)) {
    for (const specifier of match[1].split(',')) {
      const exportedName = specifier.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0];
      if (exportedName) requested.add(exportedName);
    }
  }
}

const library = await readFile(libraryEntry, 'utf8');
const paths = new Map();
for (const match of library.matchAll(/export\s*{([^}]+)}\s*from\s*['"]([^'"]+)['"];?/g)) {
  for (const specifier of match[1].split(',')) {
    const parts = specifier.trim().split(/\s+as\s+/);
    const exportedName = parts.at(-1);
    if (exportedName) paths.set(exportedName, match[2]);
  }
}

const typeNames = new Set(['LucideIcon', 'LucideProps']);
const missing = [...requested].filter((name) => !typeNames.has(name) && !paths.has(name));
if (missing.length) throw new Error(`Unmapped Lucide exports: ${missing.join(', ')}`);

const lines = [
  '// Generated by scripts/generate-lucide-barrel.mjs. Do not edit manually.',
  'export type { LucideIcon, LucideProps } from "lucide-react";',
  ...[...requested]
    .filter((name) => !typeNames.has(name))
    .sort()
    .map((name) => `export { default as ${name} } from "lucide-react/dist/esm/${paths.get(name).replace('./', '')}";`),
  '',
];
await writeFile(output, lines.join('\n'));

for (const file of files) {
  const contents = await readFile(file, 'utf8');
  const updated = contents.replace(/(['"])lucide-react\1/g, '$1@/lib/icons$1');
  if (updated !== contents) await writeFile(file, updated);
}

console.log(`Generated ${path.relative(root, output)} with ${requested.size - [...typeNames].filter((name) => requested.has(name)).length} icons.`);
